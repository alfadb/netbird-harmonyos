//! Small self-contained encoders: JSON escaping, hex, RFC 4648 base64 and
//! SHA-256 (FIPS 180-4). No external crates — the build is offline/locked and
//! the only dependency is boringtun (never used as a library here).

// ---------------------------------------------------------------------------
// JSON
// ---------------------------------------------------------------------------

/// Escape a string for inclusion in a JSON document (quotes, backslash,
/// control chars). surrounding quotes NOT included.
pub fn json_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                out.push_str(&format!("\\u{:04x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out
}

/// `"key":"value"` fragment with escaping.
pub fn jstr(key: &str, val: &str) -> String {
    format!("\"{}\":\"{}\"", json_escape(key), json_escape(val))
}

/// `"key":<u64>` fragment.
pub fn jnum(key: &str, val: u64) -> String {
    format!("\"{}\":{}", json_escape(key), val)
}

/// `"key":<i64>` fragment.
pub fn jinum(key: &str, val: i64) -> String {
    format!("\"{}\":{}", json_escape(key), val)
}

/// `"key":true|false` fragment.
pub fn jbool(key: &str, val: bool) -> String {
    format!("\"{}\":{}", json_escape(key), val)
}

// ---------------------------------------------------------------------------
// hex
// ---------------------------------------------------------------------------

pub fn hex_lower(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        out.push(HEX[(b >> 4) as usize] as char);
        out.push(HEX[(b & 0x0f) as usize] as char);
    }
    out
}

// ---------------------------------------------------------------------------
// base64 (RFC 4648 standard alphabet, with '=' padding)
// ---------------------------------------------------------------------------

const B64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

pub fn base64(data: &[u8]) -> String {
    let mut out = String::with_capacity((data.len() + 2) / 3 * 4);
    let mut chunks = data.chunks_exact(3);
    for c in &mut chunks {
        let n = ((c[0] as u32) << 16) | ((c[1] as u32) << 8) | c[2] as u32;
        out.push(B64[((n >> 18) & 63) as usize] as char);
        out.push(B64[((n >> 12) & 63) as usize] as char);
        out.push(B64[((n >> 6) & 63) as usize] as char);
        out.push(B64[(n & 63) as usize] as char);
    }
    let rem = chunks.remainder();
    match rem.len() {
        1 => {
            let n = (rem[0] as u32) << 16;
            out.push(B64[((n >> 18) & 63) as usize] as char);
            out.push(B64[((n >> 12) & 63) as usize] as char);
            out.push('=');
            out.push('=');
        }
        2 => {
            let n = ((rem[0] as u32) << 16) | ((rem[1] as u32) << 8);
            out.push(B64[((n >> 18) & 63) as usize] as char);
            out.push(B64[((n >> 12) & 63) as usize] as char);
            out.push(B64[((n >> 6) & 63) as usize] as char);
            out.push('=');
        }
        _ => {}
    }
    out
}

