/// Sanitize an arbitrary external string (dlerror text, paths) for safe inline
/// inclusion in a `|`-separated marker field: strip NULs and control chars,
/// escape the separator and newline, cap length. Full verbatim text always
/// travels via the CHUNK channel.
pub fn sanitize_marker_field(s: &str, cap: usize) -> String {
    let mut out = String::with_capacity(s.len().min(cap));
    for ch in s.chars() {
        if out.len() >= cap {
            break;
        }
        match ch {
            '|' => out.push_str("\\x7c"),
            '\n' => out.push_str("\\x0a"),
            '\r' => out.push_str("\\x0d"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => out.push(' '),
            c => out.push(c),
        }
    }
    out
}
